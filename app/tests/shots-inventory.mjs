// Headless check of the Inventory view: node tests/shots-inventory.mjs <outDir>  (needs `serve` + `vite` running)
import { chromium } from 'playwright-core'
import { homedir } from 'node:os'

const out = process.argv[2] ?? '.'
const exe = `${homedir()}/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell`
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1480, height: 960 } })
page.on('console', (m) => m.type() === 'error' && console.log('console:', m.text()))
page.on('pageerror', (e) => console.log('pageerror:', e.message))
await page.addInitScript(() => localStorage.setItem('dr-planner.lang', 'fr'))
await page.goto('http://localhost:5173/')
await page.waitForSelector('.row', { timeout: 30000 })
await page.waitForTimeout(800)
await page.getByRole('button', { name: 'Inventaire' }).click()
await page.waitForSelector('.tabs .tab', { timeout: 30000 })
await page.waitForTimeout(600)
console.log('tabs:', (await page.locator('.panel .tabs .tab').allTextContents()).join(' | '))
await page.screenshot({ path: `${out}/inv-1.png` })
// Wanted stats: the objective's priorities, then the build evaluation.
await page.waitForSelector('button:has-text("Mes priorités"):not([disabled])', { timeout: 30000 })
await page.getByRole('button', { name: 'Mes priorités' }).click()
await page.waitForTimeout(300)
console.log('wanted:', (await page.locator('.chip').allTextContents()).join(' | '))
await page.getByRole('button', { name: 'Évaluer les objets' }).click()
await page.waitForSelector('.slot .gain', { timeout: 60000 })
await page.locator('.slot:not(.empty)').first().click()
await page.waitForTimeout(400)
await page.screenshot({ path: `${out}/inv-2.png` })
await page.getByLabel('Trier par gain').check()
await page.waitForTimeout(300)
await page.locator('.slot:not(.empty)').first().click()
await page.waitForTimeout(300)
await page.screenshot({ path: `${out}/inv-3.png` })
console.log('detail:', (await page.locator('.detail').textContent())?.slice(0, 300))
await page.getByRole('button', { name: 'Essayer dans le build' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/inv-4.png` })
console.log('after try: cr', await page.locator('.cr').textContent(), await page.locator('.cr-delta').textContent().catch(() => ''))
await browser.close()
